import { DraftReport, StaffMember } from '../types';

const API_BASE = '/api/ai-office';

export const apiClient = {
  /**
   * Retrieves all 9 virtual staff members
   */
  async getStaff(): Promise<StaffMember[]> {
    const res = await fetch(`${API_BASE}/staff`);
    if (!res.ok) throw new Error(`Failed to fetch staff: ${res.statusText}`);
    const data = await res.json();
    return data.staff || [];
  },

  /**
   * Dispatches an executive task to the AI office
   */
  async dispatchTask(
    taskPrompt: string,
    staffHint?: string,
    divisionHint?: string
  ): Promise<DraftReport> {
    const res = await fetch(`${API_BASE}/dispatch`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ taskPrompt, staffHint, divisionHint }),
    });
    if (!res.ok) throw new Error(`Dispatch failed: ${res.statusText}`);
    const data = await res.json();
    return data.draft;
  },

  /**
   * Sends draft revision notes from Bos Ismanto to staff
   */
  async reviseDraft(
    draftId: string,
    previousDraft: string,
    revisionNotes: string,
    staffName: string,
    divisionName: string
  ): Promise<{ hasilDraf: string; formattedReport: string; revisionNotes: string }> {
    const res = await fetch(`${API_BASE}/revise`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ draftId, previousDraft, revisionNotes, staffName, divisionName }),
    });
    if (!res.ok) throw new Error(`Revision failed: ${res.statusText}`);
    const data = await res.json();
    return data.revisedDraft;
  },

  /**
   * Fetches autonomous drafts generated by backend background scanner
   */
  async getProactiveDrafts(): Promise<DraftReport[]> {
    const res = await fetch(`${API_BASE}/proactive`);
    if (!res.ok) throw new Error(`Failed to fetch proactive drafts: ${res.statusText}`);
    const data = await res.json();
    return data.proactiveDrafts || [];
  },

  /**
   * Manually triggers an autonomous batch radar scan
   */
  async triggerProactiveScan(): Promise<DraftReport[]> {
    const res = await fetch(`${API_BASE}/proactive/scan`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
    });
    if (!res.ok) throw new Error(`Scan trigger failed: ${res.statusText}`);
    const data = await res.json();
    return data.proactiveReports || [];
  },

  /**
   * Triggers the 06.00 AM autonomous cycle for Divisi Content Creator (Trendy + Script-AI + Clipper)
   */
  async triggerDailyCreatorRoutine(topic?: string): Promise<DraftReport> {
    const res = await fetch(`${API_BASE}/creator/daily-routine`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ topic }),
    });
    if (!res.ok) throw new Error(`Daily creator routine failed: ${res.statusText}`);
    const data = await res.json();
    return data.report;
  },
};
